"""Independent local Hartree--Fock contractions for PKA1 compensation terms.

These are the *additional* phenomenological contact interactions of RHF-e
Eqs. (3.204) and (3.293).  They are not generated by differentiating the
finite-range Green kernel.  The latter has its own distributional Hessian
term, which remains in the finite-range derivative operator.

The module uses local one-body density matrices, so it is valid for complex,
time-reversal-breaking spinors.  It deliberately exposes direct and exchange
pieces separately; spherical trace-reduced formulas are only a regression
limit, not assumed as the general three-dimensional expression.
"""
from __future__ import annotations

import torch

from .currents import _gamma_matrices


def _density_matrices(spinors: dict[str, torch.Tensor],
                      rho_active: dict[str, torch.Tensor]) -> dict[str, torch.Tensor]:
    if set(spinors) != {"n", "p"} or set(rho_active) != {"n", "p"}:
        raise ValueError("contact functional requires neutron and proton samples")
    result = {}
    for species in ("n", "p"):
        q, rho = spinors[species], rho_active[species]
        if q.ndim != 3 or q.shape[1] != 4 or rho.shape != (q.shape[2], q.shape[2]):
            raise ValueError("spinors must be [P,4,M], with matching active density")
        if q.dtype != torch.complex128 or rho.dtype != torch.complex128 or q.device != rho.device:
            raise ValueError("spinors and active densities must be complex128 on one device")
        result[species] = torch.einsum("ab,pia,pjb->pij", rho, q, q.conj())
    return result


def _contact_energy(spinors: dict[str, torch.Tensor],
                    rho_active: dict[str, torch.Tensor], weights: torch.Tensor,
                    vertex: torch.Tensor, *, kind: str,
                    hbar_c_mev_fm: float) -> dict[str, torch.Tensor]:
    """Evaluate 1/2*(1/3) direct-minus-exchange contact expectation.

    ``vertex[p]`` is the local coefficient with dimensions fm.  The returned
    direct and exchange energies are in MeV.  Neutron/proton direct isospin
    contractions use tau_3=(+1,-1); exchange contractions use
    T_nn=T_pp=1,T_np=T_pn=2, as in the source's no-charge-exchange RHFB
    reduction.
    """
    d = _density_matrices(spinors, rho_active)
    pcount = d["n"].shape[0]
    if d["p"].shape[0] != pcount or weights.shape != (pcount,) or vertex.shape != (pcount,):
        raise ValueError("contact point arrays must have matching point counts")
    if weights.dtype != torch.float64 or vertex.dtype != torch.float64:
        raise TypeError("weights and contact vertex must use float64")
    if weights.device != d["n"].device or vertex.device != d["n"].device:
        raise ValueError("all contact inputs must be on the same device")
    gamma, gamma5 = _gamma_matrices(device=d["n"].device, dtype=torch.complex128)
    g0 = gamma[0]
    if kind == "rho_tensor":
        # H_delta = +1/6 (f_rho/2M)^2 (bar psi sigma^{mu i} tau psi)
        #                                      (bar psi sigma_{mu i} tau psi).
        # The spatial index is contracted with the Euclidean dot product;
        # lowering mu supplies its Minkowski sign.
        vertices = []
        for mu in range(4):
            mu_sign = (1.0, -1.0, -1.0, -1.0)[mu]
            for i in range(1, 4):
                sigma = 0.5j * (gamma[mu] @ gamma[i] - gamma[i] @ gamma[mu])
                vertices.append((g0 @ sigma, -mu_sign))
    elif kind == "pion_pv":
        # H_delta = +1/6 (f_pi/m_pi)^2 (bar psi gamma5 gamma^k tau psi)^2.
        vertices = [(g0 @ gamma5 @ gamma[k], 1.0) for k in range(1, 4)]
    else:
        raise ValueError("kind must be rho_tensor or pion_pv")

    direct_density = torch.zeros(pcount, dtype=torch.float64, device=weights.device)
    exchange_density = torch.zeros_like(direct_density)
    species = ("n", "p")
    direct_t3 = {"n": 1.0, "p": -1.0}
    # 1/2 * 1/3 is the common coefficient in both compensation Hamiltonians.
    for op, contraction_sign in vertices:
        currents = {
            q: torch.einsum("pij,ji->p", d[q], op).real for q in species
        }
        for q in species:
            for r in species:
                direct_density = direct_density + (
                    (1.0 / 6.0) * contraction_sign * direct_t3[q] * direct_t3[r]
                    * currents[q] * currents[r]
                )
                isospin_exchange = 1.0 if q == r else 2.0
                exchange_density = exchange_density - (
                    (1.0 / 6.0) * contraction_sign * isospin_exchange
                    * torch.einsum("pij,jk,pkl,li->p", d[q], op, d[r], op).real
                )
    scale = hbar_c_mev_fm
    direct = scale * torch.sum(weights * vertex.square() * direct_density)
    exchange = scale * torch.sum(weights * vertex.square() * exchange_density)
    return {"direct": direct, "exchange": exchange, "total": direct + exchange}


def rho_tensor_contact_energy(spinors: dict[str, torch.Tensor],
                              rho_active: dict[str, torch.Tensor],
                              weights: torch.Tensor, f_rho_over_2m: torch.Tensor,
                              *, hbar_c_mev_fm: float) -> dict[str, torch.Tensor]:
    """PKA1 rho-T compensation; vertex is ``g_rho*f_rho/(2M)`` in fm."""
    return _contact_energy(spinors, rho_active, weights, f_rho_over_2m,
                           kind="rho_tensor", hbar_c_mev_fm=hbar_c_mev_fm)


def pion_pv_contact_energy(spinors: dict[str, torch.Tensor],
                           rho_active: dict[str, torch.Tensor],
                           weights: torch.Tensor, f_pi_over_mpi: torch.Tensor,
                           *, hbar_c_mev_fm: float) -> dict[str, torch.Tensor]:
    """PKA1 pion-PV compensation; vertex is ``f_pi/m_pi`` converted to fm."""
    return _contact_energy(spinors, rho_active, weights, f_pi_over_mpi,
                           kind="pion_pv", hbar_c_mev_fm=hbar_c_mev_fm)
